//! Writes the TypeScript bindings for every command and event to
//! `contracts/bindings/bindings.ts`. CI runs this and fails on drift
//! (docs/technology.md §6).
//!
//! ```text
//! cd src-tauri && cargo run --bin export-bindings
//! ```

use std::path::PathBuf;

use specta_typescript::Typescript;

fn main() {
    let out = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../contracts/bindings/bindings.ts"));

    // Integers export as `number` (no lossless bigints); the contract only uses f64/u32 anyway.
    let ts = Typescript::default()
        .header("// @ts-nocheck\n// GENERATED by `cargo run --bin export-bindings` in src-tauri/. Do not edit.\n// Source of truth: src-tauri/src/ipc/. Re-run after changing any command or event.\n");

    // specta's exporter recurses per type; give it room.
    let worker = std::thread::Builder::new()
        .stack_size(256 * 1024 * 1024)
        .spawn(move || {
            loop_dock_lib::ipc::builder().export(ts, &out).expect("export bindings");
            println!("wrote {}", out.display());
        })
        .expect("spawn exporter");
    worker.join().expect("exporter panicked");
}
